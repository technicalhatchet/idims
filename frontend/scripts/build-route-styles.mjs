import { execSync } from 'child_process';
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'public', 'styles');
const manifestPath = path.join(root, 'lib', 'routeStylesAssets.js');
const diagnosticsTmp = path.join(outDir, '.diagnostics-utilities.tmp.css');

const ROUTE_CSS_PATTERN = /^(diagnostics-utilities|solomon-theme)(\.[a-f0-9]{8})?\.css$/;

function contentHash(buffer) {
  return crypto.createHash('sha256').update(buffer).digest('hex').slice(0, 8);
}

function purgeStaleRouteCss(keepFilenames) {
  if (!fs.existsSync(outDir)) {
    return;
  }
  const keep = new Set(keepFilenames);
  for (const name of fs.readdirSync(outDir)) {
    if (!ROUTE_CSS_PATTERN.test(name)) {
      continue;
    }
    if (!keep.has(name)) {
      fs.unlinkSync(path.join(outDir, name));
    }
  }
}

fs.mkdirSync(outDir, { recursive: true });

execSync(
  'npx tailwindcss -c tailwind.diagnostics.config.js -i ./styles/diagnostics-utilities.css -o ./public/styles/.diagnostics-utilities.tmp.css --minify',
  { cwd: root, stdio: 'inherit' }
);

const diagnosticsBody = fs.readFileSync(diagnosticsTmp);
const solomonBody = fs.readFileSync(path.join(root, 'styles', 'solomon-theme.css'));

const diagnosticsName = `diagnostics-utilities.${contentHash(diagnosticsBody)}.css`;
const solomonName = `solomon-theme.${contentHash(solomonBody)}.css`;

fs.writeFileSync(path.join(outDir, diagnosticsName), diagnosticsBody);
fs.writeFileSync(path.join(outDir, solomonName), solomonBody);
fs.unlinkSync(diagnosticsTmp);

purgeStaleRouteCss([diagnosticsName, solomonName]);

const manifest = `// Generated by scripts/build-route-styles.mjs — do not edit.
export const ROUTE_STYLESHEETS = {
  solomonTheme: '/styles/${solomonName}',
  diagnosticsUtilities: '/styles/${diagnosticsName}',
};
`;

fs.writeFileSync(manifestPath, manifest);

console.log(`[route-styles] ${solomonName}, ${diagnosticsName}`);
